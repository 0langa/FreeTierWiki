// One-time content migration for the Phase 1 redesign (2026-09-25). Safe to re-run.
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const ROOT = process.cwd();
const CONTENT = path.join(ROOT, "content");

// Not free tiers: frameworks, docs, courses, consumer chat and meeting apps.
const REMOVE = [
  "services/next-js",
  "services/astro",
  "services/monix",
  "services/khan-academy",
  "services/deeplearning-ai-short-courses",
  "resources/react-documentation",
  "resources/django-tutorial-dev",
  "resources/w3schools",
  "resources/freecodecamp",
  "resources/the-odin-project",
  "resources/full-stack-open",
  "resources/mit-opencourseware",
  "resources/edx",
  "resources/roadmap-sh",
  "resources/cisco-networking-academy",
  "resources/devnet-academy",
  "resources/labex",
  "resources/discord",
  "resources/telegram",
  "resources/zoom-us",
  "resources/webex",
  "resources/whereby-com",
  "resources/meet-jit-si",
  "resources/revolt-chat",
  "resources/gitter-im",
  "resources/substack",
];

// Real SaaS free plans that were filed as "resources".
const MOVE_TO_SERVICES = [
  "gitbook",
  "hackmd-io",
  "mintlify",
  "notion",
  "nuclino",
  "zoho-docs",
  "zoho-wiki",
  "docssearch",
  "zulip",
  "rocket-chat",
  "twist-com",
  "azure-ai-machine-learning",
  "dynamicdocs",
];

const TOP_LISTS = ["useCases", "bestFor", "avoidIf", "quickstartSteps", "tags", "sourceUrls", "subtypes"];
const DETAIL_LISTS = ["limits", "caveats", "billingRiskNotes"];

const fileOf = (rel) => path.join(CONTENT, `${rel}.mdx`);
const report = [];

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const full = path.join(dir, d.name);
    return d.isDirectory() ? walk(full) : d.name.endsWith(".mdx") ? [full] : [];
  });
}

// 1. Remove
for (const rel of REMOVE) {
  if (fs.existsSync(fileOf(rel))) {
    fs.rmSync(fileOf(rel));
    report.push(`removed ${rel}`);
  }
}

// 2. Move resources → services
for (const slug of MOVE_TO_SERVICES) {
  const from = fileOf(`resources/${slug}`);
  const to = fileOf(`services/${slug}`);
  if (!fs.existsSync(from)) continue;
  if (fs.existsSync(to)) throw new Error(`services/${slug} already exists; refusing to overwrite`);
  fs.renameSync(from, to);
  report.push(`moved resources/${slug} -> services/${slug}`);
}
const resourcesDir = path.join(CONTENT, "resources");
if (fs.existsSync(resourcesDir)) {
  const left = fs.readdirSync(resourcesDir);
  if (left.length) throw new Error(`content/resources still has: ${left.join(", ")}`);
  fs.rmdirSync(resourcesDir);
  report.push("removed empty content/resources/");
}

// 3. Rewrite list items that YAML parsed as objects ("Key: value")
const toText = (item) =>
  item && typeof item === "object" && !Array.isArray(item)
    ? Object.entries(item)
        .map(([key, value]) => `${key}: ${value}`)
        .join("; ")
    : item;
for (const file of walk(CONTENT)) {
  const parsed = matter(fs.readFileSync(file, "utf8"));
  let changed = false;
  const fix = (holder, key) => {
    if (!Array.isArray(holder?.[key])) return;
    const next = holder[key].map(toText);
    if (next.some((value, i) => value !== holder[key][i])) {
      holder[key] = next;
      changed = true;
    }
  };
  TOP_LISTS.forEach((key) => fix(parsed.data, key));
  DETAIL_LISTS.forEach((key) => fix(parsed.data.freeTierDetails, key));
  if (changed) {
    fs.writeFileSync(file, matter.stringify(parsed.content, parsed.data));
    report.push(`fixed list items in ${path.relative(CONTENT, file)}`);
  }
}

// 4. Redirects for removed and moved URLs (Cloudflare Pages _redirects format)
const rules = [
  "# Generated by scripts/migrations/2026-09-phase1-content.mjs on 2026-09-25.",
  ...MOVE_TO_SERVICES.flatMap((slug) => [`/resources/${slug}/ /services/${slug}/ 301`, `/resources/${slug} /services/${slug}/ 301`]),
  ...REMOVE.filter((rel) => rel.startsWith("services/")).flatMap((rel) => [`/${rel}/ /explorer/ 301`, `/${rel} /explorer/ 301`]),
  "/resources/* /explorer/ 301",
];
fs.writeFileSync(path.join(ROOT, "public", "_redirects"), `${rules.join("\n")}\n`);
report.push(`wrote public/_redirects (${rules.length - 1} rules)`);

console.log(report.join("\n"));
